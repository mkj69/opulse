    function worldExample(name) {
      const example = WORLD_EXAMPLES[name];
      if (example) return example;
      const data = state.worldData[name];
      const operators = (data && data.operators) || [];
      const sample = data && data.examples && data.examples.find((item) => item.operator);
      const first = sample && operators.find((item) => item.name === sample.operator);
      if (first && name !== "action") {
        const needed = new Set();
        function include(operator) {
          if (needed.has(operator.name)) return;
          needed.add(operator.name);
          const body = operator.definition.split("=").slice(1).join("=");
          operators.forEach((candidate) => {
            if (candidate.name !== operator.name && body.includes(candidate.name)) include(candidate);
          });
        }
        include(first);
        const definitions = operators.filter((operator) => needed.has(operator.name)).map((operator) => operator.definition).join("\n");
        return { definitions, expression: sample.expression,
          note: sample.plain || `This definition applies an operator from the ${name} world.` };
      }
      return { definitions: "a ◇ = { a }", expression: "3 ◇",
        note: `This definition returns its input in the ${name} world.` };
    }
    function loadRenderer(name) {
      if (!name || !/^[a-z][a-z0-9_]*$/.test(name)) return;
      const path = SCRIPT_SRC ? new URL(`worlds/${name}.js`, SCRIPT_SRC).href : `assets/js/worlds/${name}.js`;
      const dataPath = SCRIPT_SRC ? new URL(`../data/worlds/${name}.json`, SCRIPT_SRC).href : `assets/data/worlds/${name}.json`;
      const worlds = window.OpulseWorlds = window.OpulseWorlds || {};
      if (!worlds.register) worlds.register = (key, renderer) => { worldRenderers[key] = renderer; };
      else if (!worlds._opgWrapped) {
        const original = worlds.register;
        worlds.register = (key, renderer) => { worldRenderers[key] = renderer; return original(key, renderer); };
        worlds._opgWrapped = true;
      }
      if (!worlds.fallbackValue) worlds.fallbackValue = (element, value) => {
        element.textContent = worlds.valueText(value);
      };
      if (!worlds.valueText) worlds.valueText = (value) => {
        if (!value || value.t === "nan") return "NaN";
        if (value.t === "str") return JSON.stringify(value.v);
        if (value.t === "list") return `[${value.v.map(worlds.valueText).join(", ")}]`;
        return String(value.v);
      };
      if (WORLD_EXAMPLES[name]) return; // shipped worlds have no renderer or data files
      loadScript(path).then(() => {
        if (state.out && state.out.ok && ui.world.value === name) renderWorldValue(state.out.value);
      }).catch(() => {});
      fetch(dataPath).then((response) => response.ok ? response.json() : null).then((data) => {
        if (data) state.worldData[name] = data;
        if (data && ui.world.value === name && ui.mode.value === "hide") renderHideTargets();
        if (data && ui.world.value === name && ui.defs.value === "a ◇ = { a }" && ui.expr.value === "3 ◇") {
          const example = worldExample(name);
          ui.defs.value = example.definitions;
          ui.expr.value = example.expression;
          ui.note.textContent = example.note;
          changed(true);
        }
        if (state.out && state.out.ok && ui.world.value === name) renderWorldValue(state.out.value);
      }).catch(() => {});
    }
    function valueObject(value) {
      if (value === "NaN") return { t: "nan" };
      if (value === "true" || value === "false") return { t: "bool", v: value === "true" };
      try {
        const parsed = JSON.parse(value);
        if (Array.isArray(parsed)) return { t: "list", v: parsed.map((item) => ({ t: "int", v: item })) };
        if (typeof parsed === "string") return { t: "str", v: parsed };
        if (typeof parsed === "number") return { t: "int", v: parsed };
      } catch (err) { /* keep text fallback */ }
      return { t: "str", v: value };
    }
    function renderWorldValue(value) {
      const renderer = state.renderers[ui.world.value];
      const target = $(ui.result, ".opg-world-value");
      if (!target) return;
      target.replaceChildren();
      if (renderer && renderer.renderValue) {
        try { renderer.renderValue(target, valueObject(value), state.worldData[ui.world.value]); return; }
        catch (err) { target.replaceChildren(); }
      }
      target.remove();
    }

