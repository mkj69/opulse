    function writeHash() {
      if (ui.mode.value === "hide") {
        const hidden = state.hidden && state.hidden.id || state.pendingHidden;
        const example = !ui.world.value && matchingExample();
        const hash = `#hide=1${ui.world.value ? `&w=${encodeURIComponent(ui.world.value)}` : ""}` +
          `${example ? `&example=${encodeURIComponent(example.id)}` : ""}${hidden ? `&target=${encodeURIComponent(hidden)}` : ""}` +
          `${state.customAtoms.length ? `&a=${encode(JSON.stringify(state.customAtoms))}` : ""}` +
          `${isEmptyConfig(state.config) ? "" : `&c=${encode(JSON.stringify(state.config))}`}` +
          `${growState() ? `&g=${encode(JSON.stringify(growState()))}` : ""}`;
        if (location.hash !== hash) {
          try { history.replaceState(history.state, "", location.pathname + location.search + hash); } catch (err) { /* local file */ }
        }
        return;
      }
      const ex = matchingExample();
      const g = growState();
      const extra = (ui.world.value ? `&w=${encodeURIComponent(ui.world.value)}` : "") +
        (state.customAtoms.length ? `&a=${encode(JSON.stringify(state.customAtoms))}` : "") +
        (isEmptyConfig(state.config) ? "" : `&c=${encode(JSON.stringify(state.config))}`) +
        (g ? `&g=${encode(JSON.stringify(g))}` : "");
      const hash = ex && !g ? `#example=${encodeURIComponent(ex.id)}` : `#d=${encode(ui.defs.value)}&e=${encode(ui.expr.value)}${extra}`;
      if (location.hash !== hash) {
        try { history.replaceState(history.state, "", location.pathname + location.search + hash); } catch (err) { /* file: URLs in some browsers */ }
      }
    }
    function readHash() {
      const params = new URLSearchParams(location.hash.replace(/^#/, ""));
      const world = params.get("w") || "";
      if (world && !state.worlds.includes(world)) return false;
      ui.world.value = world;
      try {
        state.customAtoms = params.has("a") ? JSON.parse(decode(params.get("a"))) : [];
        if (!Array.isArray(state.customAtoms)) throw new Error("invalid atoms");
        const config = params.has("c") ? JSON.parse(decode(params.get("c"))) : {};
        state.config = Object.assign(emptyConfig(), config);
        const g = params.has("g") ? JSON.parse(decode(params.get("g"))) : DEFAULT_GROW;
        ui.growLayers.value = g.layers || DEFAULT_GROW.layers;
        ui.growSeed.value = String(g.seed !== undefined ? g.seed : DEFAULT_GROW.seed);
      } catch (err) { state.customAtoms = []; state.config = emptyConfig(); return false; }
      loadRenderer(world);
      if (params.get("hide") === "1") {
        if (world) {
          const example = worldExample(world);
          ui.defs.value = example.definitions;
          ui.expr.value = example.expression;
          ui.note.textContent = example.note;
        } else if (!applyExample(params.get("example"))) applyExample(state.examples.length ? state.examples[0].id : "");
        state.pendingHidden = params.get("target") || "";
        state.hiddenChosen = !!state.pendingHidden;
        ui.mode.value = "hide";
        ui.hideCard.hidden = false;
        root.classList.add("opg-hide-mode");
        return true;
      }
      if (params.has("example") && applyExample(params.get("example"))) return true;
      if (params.has("d") || params.has("e")) {
        try {
          ui.defs.value = params.has("d") ? decode(params.get("d")) : "";
          ui.expr.value = params.has("e") ? decode(params.get("e")) : "";
          ui.preset.value = "";
          ui.note.textContent = "";
          updateGutter();
          return true;
        } catch (err) { return false; }
      }
      return false;
    }
