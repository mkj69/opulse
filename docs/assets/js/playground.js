  function explain(step, atomRules) {
    const args = step.parameters.map((p) => `${p.name} = ${p.value}`).join(", ");
    const parts = [];
    if (step.kind === "eval") {
      const rule = atomRules[`${step.symbol}|${step.shape}`];
      parts.push(`<p>Compute <code>${esc(step.before.slice(step.focus[0], step.focus[1]).replace(/^\((.*)\)$/, "$1"))}</code> = <b>${esc(step.output)}</b>` +
        (step.atom ? ` with the atom <i>${esc(step.atom)}</i>.` : ".") + "</p>");
      if (rule) parts.push(`<p class="opg-dim">${esc(rule)}</p>`);
    } else {
      const kind = { simple: "simple", branch: "branch", recursive: "recursive" }[step.operator_kind] || "";
      parts.push(`<p>${step.kind === "expand" ? "Unfold" : "Try to unfold"} the ${kind} operator <code>${esc(shapeLabel(step.symbol, step.shape))}</code>` +
        (args ? ` with ${esc(args)}` : "") + ".</p>");
      const rows = step.branches || [];
      const conditional = rows.some((b) => b.condition !== null);
      if (conditional) {
        const plain = (c) => c.op ? `${c.left} ${c.op} ${c.right}` : c.left;
        parts.push('<ol class="opg-branches">' + rows.map((b) => {
          const chosen = step.branch_index === b.index;
          const cond = b.condition === null
            ? `<span class="opg-kw">else</span>`
            : `<code>${esc(b.substituted)}</code> ${verdict(b.truth)}` +
              (b.comparisons.some((c) => c.text !== plain(c))
                ? ` <span class="opg-dim">(${b.comparisons.map((c) => esc(plain(c))).join(", ")})</span>` : "");
          return `<li value="${b.index}" class="${chosen ? "opg-chosen" : ""}"><span class="opg-bn">branch ${b.index}</span> ${cond}` +
            (chosen ? ` <span class="opg-arrow">takes</span> <code>${esc(b.body)}</code>` : "") + "</li>";
        }).join("") + "</ol>");
        if (step.kind === "expand") {
          const taken = rows.find((b) => b.index === step.branch_index);
          parts.push(`<p class="opg-dim">Branch ${step.branch_index} of ${step.branch_count} is taken because ` +
            (taken && taken.condition === null ? "no earlier condition holds." : "its condition is the first that holds.") + "</p>");
        }
      }
    }
    if (step.nan_cause) parts.push(`<p class="opg-nan-cause">${esc(NAN_TEXT[step.nan_cause] || "")}</p>`);
    return parts.join("");
  }

  // ------------------------------------------------------------------ graph
  function graphSVG(graph) {
    if (!graph || !graph.nodes.length) return '<p class="opg-dim">The expression uses no operators.</p>';
    const cols = {};
    graph.nodes.forEach((n) => { (cols[n.column] = cols[n.column] || []).push(n); });
    const order = Object.keys(cols).map(Number).sort((a, b) => a - b);
    const charW = 8.4, padX = 14, boxH = 30, gapY = 14, gapX = 56, top = 48;
    const pos = {};
    let x = 12, height = 0;
    order.forEach((c) => {
      const nodes = cols[c].sort((a, b) => (a.kind === "atom") - (b.kind === "atom") || (a.line || 0) - (b.line || 0) || a.symbol.localeCompare(b.symbol));
      const width = Math.max(...nodes.map((n) => [...shapeLabel(n.symbol, n.shape)].length * charW + 2 * padX), 64);
      nodes.forEach((n, i) => {
        const y = top + i * (boxH + gapY);
        pos[n.id] = { x, y, w: width, n };
        height = Math.max(height, y + boxH);
      });
      x += width + gapX;
    });
    const width = x - gapX + 12;
    let edges = "";
    graph.edges.forEach((e) => {
      const a = pos[e.source], b = pos[e.target];
      if (!a || !b) return;
      const used = a.n.used && b.n.used ? " opg-edge-used" : "";
      if (e.source === e.target) {
        const cx = a.x + a.w / 2;
        edges += `<path class="opg-edge opg-edge-self${used}" d="M ${cx - 9} ${a.y} C ${cx - 22} ${a.y - 22}, ${cx + 22} ${a.y - 22}, ${cx + 9} ${a.y}" marker-end="url(#opg-arrow)"/>`;
        return;
      }
      const x1 = a.x, y1 = a.y + boxH / 2, x2 = b.x + b.w, y2 = b.y + boxH / 2, mx = (x1 + x2) / 2;
      edges += `<path class="opg-edge${used}" d="M ${x1} ${y1} C ${mx} ${y1}, ${mx} ${y2}, ${x2 + 4} ${y2}" marker-end="url(#opg-arrow)"/>`;
    });
    let nodes = "";
    Object.values(pos).forEach(({ x: nx, y, w, n }) => {
      const tip = n.definition || n.rule || "";
      const focusable = n.line ? ` tabindex="0" role="button" data-line="${n.line}" aria-label="${esc(shapeLabel(n.symbol, n.shape))}, line ${n.line}"` : "";
      nodes += `<g class="opg-node opg-k-${n.kind}${n.used ? " opg-used" : ""}"${focusable}>` +
        `<title>${esc(tip)}</title><rect x="${nx}" y="${y}" width="${w}" height="${boxH}" rx="8"/>` +
        `<text x="${nx + w / 2}" y="${y + boxH / 2 + 5}">${esc(shapeLabel(n.symbol, n.shape))}</text></g>`;
    });
    const labels = order.map((c) => {
      const first = pos[cols[c][0].id];
      return `<text class="opg-col" x="${first.x + 2}" y="16">depth ${c}</text>`;
    }).join("");
    return `<svg class="opg-svg" viewBox="0 0 ${width} ${height + 12}" width="${width}" height="${height + 12}" role="img" aria-label="Dependency graph">` +
      '<defs><marker id="opg-arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M 0 0 L 10 5 L 0 10 z"/></marker></defs>' +
      labels + edges + nodes + "</svg>";
  }

