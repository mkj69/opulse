"""Package the Python files the documentation playground runs, and its example presets.

    python tools/build_playground.py             # refresh docs/assets/playground/opulse_bundle.js
    python tools/build_playground.py --check     # exit 1 if the bundle differs from src/
    python tools/build_playground.py --examples  # also regenerate examples.js (needs z3)

The playground page (docs/guide/playground.md) runs ``opulse.playground`` under Pyodide. The
bundle holds the modules that ``import opulse.playground`` and every world load, read from src/, as a
base64 zip inside a JavaScript file, so the page also works when opened from disk. The bundle
also holds the generation pipeline, which grows operators without z3 when its two solver checks
are off. The browser import must not load z3 or PyYAML; this script and tests/test_playground.py
check that. Relations gets a JSON copy of its default YAML table for Pyodide.

The examples file holds hand-written presets and presets taken from an operator set generated
with a fixed seed. Every preset stores the value the playground computes for it, and
tests/test_playground.py checks those values.
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import os
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
OUT = ROOT / "docs" / "assets" / "playground"
BUNDLE = OUT / "opulse_bundle.js"
EXAMPLES = OUT / "examples.js"
FORBIDDEN = ("z3", "yaml")  # must not be imported by the page

_PROBE = """
import importlib, json, pkgutil, sys
import opulse.playground
import opulse.presets
import opulse.core.presets
import opulse.worlds
# Grow and export import some modules on first use, so the probe imports and runs them.
import opulse.definition.complexity, opulse.definition.typecheck, opulse.generation.typed  # noqa: E401
for world in ("", "integer", "atomic", "successor", "bits", "strings", "lists"):
    assert opulse.playground.grow(world, layers="2 1", seed=1)["ok"], world
    assert opulse.playground.export(world)["ok"], world
for module in pkgutil.walk_packages(opulse.worlds.__path__, opulse.worlds.__name__ + "."):
    importlib.import_module(module.name)
mods = sorted(name for name in sys.modules if name == "opulse" or name.startswith("opulse."))
files = [sys.modules[name].__file__ for name in mods]
print(json.dumps({"files": files, "forbidden": [m for m in %r if m in sys.modules]}))
"""


def closure() -> list[str]:
    """Paths (relative to src/) of every opulse module the page imports (see ``_PROBE``)."""
    env = dict(os.environ, PYTHONPATH=str(SRC))
    out = subprocess.run([sys.executable, "-c", _PROBE % (FORBIDDEN,)], env=env, check=True,
                         capture_output=True, text=True).stdout
    data = json.loads(out)
    if data["forbidden"]:
        raise SystemExit(f"opulse.playground imports {data['forbidden']}; make those imports lazy")
    return sorted(Path(f).resolve().relative_to(SRC).as_posix() for f in data["files"])


def zip_bytes(files: dict[str, bytes]) -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for rel, content in sorted(files.items()):
            info = zipfile.ZipInfo(rel, date_time=(1980, 1, 1, 0, 0, 0))
            info.external_attr = 0o644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, content)
    return buffer.getvalue()


def read_bundle(path: Path = BUNDLE) -> dict[str, bytes]:
    """The files inside a written bundle: path -> content."""
    text = path.read_text(encoding="utf-8")
    payload = json.loads(text[text.index("{"): text.rindex("}") + 1])
    with zipfile.ZipFile(io.BytesIO(base64.b64decode(payload["zip"]))) as archive:
        return {name: archive.read(name) for name in archive.namelist()}


def expected_files() -> dict[str, bytes]:
    files = {rel: (SRC / rel).read_bytes() for rel in closure()}
    import yaml

    table = yaml.safe_load((ROOT / "configs" / "presets" / "rel.yaml").read_text(encoding="utf-8"))
    files["opulse/worlds/data/rel.json"] = (json.dumps(table, ensure_ascii=False, sort_keys=True)
                                           + "\n").encode("utf-8")
    return files


def write_bundle() -> bool:
    """Write the bundle if its contents differ from src/; return True if it was written."""
    files = expected_files()
    if BUNDLE.exists() and read_bundle() == files:
        return False
    from opulse import __version__

    payload = {"version": __version__, "files": sorted(files),
               "zip": base64.b64encode(zip_bytes(files)).decode("ascii")}
    OUT.mkdir(parents=True, exist_ok=True)
    BUNDLE.write_text("/* Generated by tools/build_playground.py from src/opulse. Do not edit. */\n"
                      f"window.OPULSE_BUNDLE = {json.dumps(payload)};\n", encoding="utf-8")
    return True


