SEED = 7
LAYERS = [8, 5, 3]


def generated_examples() -> list[dict]:
    """Presets from an operator set grown with ``build_layers`` (fixed seed)."""
    import random

    sys.path.insert(0, str(SRC))
    from opulse.config import Settings
    from opulse.core.starting_sets import starting_registry
    from opulse.generation.pipeline import OperatorFactory, build_layers
    from opulse.playground import run

    registry = starting_registry()
    factory = OperatorFactory(Settings(), registry, random.Random(SEED))
    build_layers(factory, LAYERS)
    defined = [op for op in registry.topological_order() if op.definition is not None]

    def closure_of(op) -> list:
        need, stack = set(), [op.func_id]
        while stack:
            key = stack.pop()
            if key in need or registry.get(key).definition is None:
                continue
            need.add(key)
            stack.extend(registry.get(key).dependencies)
        return [o for o in defined if o.func_id in need]

    def call(op, args) -> str:
        return op.apply_str(*map(str, args))

    picks = [
        ("generated-recursive", "Generated: a recursive operator",
         lambda o: o.definition_type == "recursive_definition"),
        ("generated-branch", "Generated: a branch operator",
         lambda o: o.definition_type == "branch_definition" and o.recursive_layer == 0),
        ("generated-layer2", "Generated: an operator on layer 2",
         lambda o: o.recursive_layer == 2 and o.definition_type != "recursive_definition"),
    ]
    examples = []
    for key, title, wanted in picks:
        for op in [o for o in defined if wanted(o)]:
            ops = closure_of(op)
            text = "\n".join(o.definition for o in ops)
            for args in ((7, 12), (13, 5), (4, 9), (21, 3)):
                expression = call(op, args[: op.n_ary])
                out = run(text, expression)
                if out["ok"] and out["value"] != "NaN" and 4 <= out["step_count"] <= 80:
                    examples.append({
                        "id": key, "group": "From a generated set", "title": title,
                        "note": f"Taken from an operator set grown with build_layers({LAYERS}) and seed {SEED}.",
                        "definitions": text, "expression": expression,
                    })
                    break
            if examples and examples[-1]["id"] == key:
                break
    whole = "\n".join(o.definition for o in defined)
    top = [o for o in defined if o.recursive_layer == 2 and o.n_ary == 2]
    if top:
        examples.append({
            "id": "generated-set", "group": "From a generated set", "title": "Generated: the whole set",
            "note": f"All {len(defined)} definitions of the generated set; edit the expression to try others.",
            "definitions": whole, "expression": call(top[0], (5, 8)),
        })
    return examples


def write_examples(include_generated: bool) -> None:
    sys.path.insert(0, str(SRC))
    from opulse.playground import run

    examples = [dict(e) for e in HAND_WRITTEN]
    if include_generated:
        examples += generated_examples()
    elif EXAMPLES.exists():
        examples += [e for e in read_examples() if e["group"] != HAND_WRITTEN[0]["group"]]
    for example in examples:
        out = run(example["definitions"], example["expression"])
        if not out["ok"]:
            raise SystemExit(f"example {example['id']} fails: {out['error']}")
        example["value"] = out["value"]
    EXAMPLES.write_text("/* Generated by tools/build_playground.py. Do not edit. */\n"
                        "window.OPULSE_PLAYGROUND_EXAMPLES = "
                        + json.dumps(examples, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")


def read_examples(path: Path = EXAMPLES) -> list[dict]:
    text = path.read_text(encoding="utf-8")
    return json.loads(text[text.index("["): text.rindex("]") + 1])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the bundle differs from src/")
    parser.add_argument("--examples", action="store_true", help="regenerate the example presets (needs z3)")
    args = parser.parse_args()
    if args.check:
        stale = not BUNDLE.exists() or read_bundle() != expected_files()
        print("playground bundle is stale" if stale else "playground bundle matches src/")
        raise SystemExit(1 if stale else 0)
    print("wrote" if write_bundle() else "unchanged", BUNDLE.relative_to(ROOT))
    if args.examples or not EXAMPLES.exists():
        write_examples(include_generated=True)
        print("wrote", EXAMPLES.relative_to(ROOT))


if __name__ == "__main__":
    main()
